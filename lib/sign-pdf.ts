import { PDFDocument, rgb, StandardFonts } from "pdf-lib";
import crypto from "crypto";

export interface SignatureInfo {
  tenantName: string;
  signerName: string;
  signerIp: string;
  signedAt: Date;
  address: string;
  leaseId: string;
}

export async function appendSignaturePage(originalPdfBytes: Uint8Array, info: SignatureInfo): Promise<Uint8Array> {
  const pdfDoc = await PDFDocument.load(originalPdfBytes);
  const helvetica = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const helveticaBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  // Hash of the original document (before we append the audit page)
  const hash = crypto.createHash("sha256").update(originalPdfBytes).digest("hex");

  const page = pdfDoc.addPage([612, 792]); // US Letter
  const { width, height } = page.getSize();
  const margin = 60;
  const contentWidth = width - margin * 2;

  let y = height - margin;

  // Header bar
  page.drawRectangle({ x: 0, y: height - 80, width, height: 80, color: rgb(0.071, 0.071, 0.071) });
  page.drawText("RentNest", { x: margin, y: height - 52, size: 22, font: helveticaBold, color: rgb(1, 1, 1) });
  page.drawText("Electronic Signature Certificate", { x: margin, y: height - 70, size: 10, font: helvetica, color: rgb(0.7, 0.7, 0.7) });

  y = height - 110;

  // Section: Signer details
  const lineHeight = 22;

  function label(text: string, val: string, yPos: number) {
    page.drawText(text, { x: margin, y: yPos, size: 9, font: helvetica, color: rgb(0.5, 0.5, 0.5) });
    page.drawText(val, { x: margin + 160, y: yPos, size: 9, font: helveticaBold, color: rgb(0.1, 0.1, 0.1) });
  }

  page.drawText("SIGNATURE DETAILS", { x: margin, y, size: 10, font: helveticaBold, color: rgb(0.3, 0.3, 0.3) });
  y -= 6;
  page.drawLine({ start: { x: margin, y }, end: { x: margin + contentWidth, y }, thickness: 0.5, color: rgb(0.85, 0.85, 0.85) });
  y -= lineHeight;

  label("Signer", info.signerName, y); y -= lineHeight;
  label("Legal name on record", info.tenantName, y); y -= lineHeight;
  label("Property", info.address, y); y -= lineHeight;
  label("Lease ID", info.leaseId, y); y -= lineHeight;
  label("Signed at", info.signedAt.toUTCString(), y); y -= lineHeight;
  label("IP address", info.signerIp, y); y -= lineHeight * 1.5;

  // Document integrity section
  page.drawText("DOCUMENT INTEGRITY", { x: margin, y, size: 10, font: helveticaBold, color: rgb(0.3, 0.3, 0.3) });
  y -= 6;
  page.drawLine({ start: { x: margin, y }, end: { x: margin + contentWidth, y }, thickness: 0.5, color: rgb(0.85, 0.85, 0.85) });
  y -= lineHeight;

  page.drawText("SHA-256 hash of original document:", { x: margin, y, size: 9, font: helvetica, color: rgb(0.5, 0.5, 0.5) });
  y -= 16;
  // Break hash across two lines so it fits
  page.drawText(hash.slice(0, 43), { x: margin, y, size: 8, font: helveticaBold, color: rgb(0.2, 0.2, 0.2) });
  y -= 14;
  page.drawText(hash.slice(43), { x: margin, y, size: 8, font: helveticaBold, color: rgb(0.2, 0.2, 0.2) });
  y -= lineHeight * 1.5;

  // Legal notice
  page.drawText("LEGAL NOTICE", { x: margin, y, size: 10, font: helveticaBold, color: rgb(0.3, 0.3, 0.3) });
  y -= 6;
  page.drawLine({ start: { x: margin, y }, end: { x: margin + contentWidth, y }, thickness: 0.5, color: rgb(0.85, 0.85, 0.85) });
  y -= lineHeight;

  const notice = [
    "This document was electronically signed in accordance with the Electronic Signatures in Global and",
    "National Commerce Act (ESIGN) and the Uniform Electronic Transactions Act (UETA). The signer",
    "confirmed their identity by entering their full legal name and provided explicit consent by checking",
    "the agreement checkbox prior to signing. This signature certificate page, together with the preceding",
    "pages, constitutes a complete and legally binding electronic record of the signed lease agreement.",
  ];
  for (const line of notice) {
    page.drawText(line, { x: margin, y, size: 8, font: helvetica, color: rgb(0.4, 0.4, 0.4) });
    y -= 13;
  }

  y -= 10;

  // Signature visual
  page.drawRectangle({ x: margin, y: y - 40, width: contentWidth, height: 50, color: rgb(0.97, 0.97, 0.97), borderColor: rgb(0.85, 0.85, 0.85), borderWidth: 0.5 });
  page.drawText(info.signerName, { x: margin + 16, y: y - 20, size: 20, font: helveticaBold, color: rgb(0.1, 0.1, 0.1) });
  page.drawText(`Signed: ${info.signedAt.toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" })}`, {
    x: margin + 16, y: y - 36, size: 8, font: helvetica, color: rgb(0.5, 0.5, 0.5),
  });

  // Footer
  page.drawText("Generated by RentNest · rentnest.app", {
    x: margin, y: 30, size: 8, font: helvetica, color: rgb(0.6, 0.6, 0.6),
  });
  page.drawText(`Page ${pdfDoc.getPageCount()} of ${pdfDoc.getPageCount()}`, {
    x: width - margin - 60, y: 30, size: 8, font: helvetica, color: rgb(0.6, 0.6, 0.6),
  });

  return pdfDoc.save();
}
